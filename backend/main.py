def health():
    return {"status": "ok", "app": "Meru", "version": "2.1.0"}


@app.post("/analyze", response_model=AnalyzeResponse)
async def analyze_frame(session_id: str, file: UploadFile):
    """
    Accepts one JPEG/PNG frame from the browser, runs MediaPipe + the
    posture classifier, applies majority-vote smoothing (5-frame buffer),
    and updates this session's rolling score. Call every ~400ms from the
    frontend for near-real-time monitoring.
    """
    contents = await file.read()
    frame = cv2.imdecode(np.frombuffer(contents, np.uint8), cv2.IMREAD_COLOR)
    if frame is None:
        raise HTTPException(400, "Could not decode image — check the upload format.")

    state = _get_session(session_id)

    # ── Dim-Lighting Detection & CLAHE Adaptive Contrast Enhancement ──
    gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
    mean_lum = float(np.mean(gray))
    is_dim = mean_lum < 75.0
    critically_dark = mean_lum < 28.0

    if is_dim:
        # Equalize luminance in LAB color space to reveal obscured joints
        lab = cv2.cvtColor(frame, cv2.COLOR_BGR2LAB)
        l_chan, a_chan, b_chan = cv2.split(lab)
        clahe = cv2.createCLAHE(clipLimit=3.0, tileGridSize=(8, 8))
        enhanced_l = clahe.apply(l_chan)
        enhanced_lab = cv2.merge((enhanced_l, a_chan, b_chan))
        frame = cv2.cvtColor(enhanced_lab, cv2.COLOR_LAB2BGR)

    frame = cv2.flip(frame, 1)
    rgb   = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
    res   = pose.process(rgb)

    if not res.pose_landmarks:
        return AnalyzeResponse(
            posture="No Pose Detected",
            spine_angle=0.0,
            shoulder_tilt=0.0,
            neck_angle=0.0,
            head_tilt=0.0,
            tip="",
            score=_rolling_score(state),
            alert=False,
            low_light=critically_dark,
            issues=[],
        )

    result  = clf.classify(res.pose_landmarks.landmark, mp_pose, baseline=state.baseline)
    posture = result["posture"]

    # Majority-vote smoothing — stops rapid flickering between labels
    state.smoothing_buf.append(posture)
    posture = Counter(state.smoothing_buf).most_common(1)[0][0]

    now = datetime.now()
    state.session_log.append((now, posture))
    state.rolling_log.append((now, posture))
    if result["spine_angle"]:
        state.spine_history.append(result["spine_angle"])

    # Sustained bad-posture alert
    alert = False
    threshold = getattr(state, "alert_threshold_s", BAD_POSTURE_ALERT_S)
    if posture not in ("Good Posture", "No Pose Detected"):
        if state.bad_start is None:
            state.bad_start = time.time()
        elif time.time() - state.bad_start >= threshold:
            alert = True
            state.bad_start = time.time()   # reset so alert re-fires periodically
    else:
        state.bad_start = None

    # Periodic 5-min auto-save
    if time.time() - state.last_report_time >= ROLLING_REPORT_INTERVAL_S:
        stats = compute_session_stats(state.rolling_log, state.spine_history)
        if stats:
            database.log_session(stats, label="5-min check")
        state.rolling_log.clear()
        state.last_report_time = time.time()

    return AnalyzeResponse(
        posture=posture,
        spine_angle=result["spine_angle"],
        shoulder_tilt=result["shoulder_tilt"],
        neck_angle=result["neck_angle"],
        head_tilt=result["head_tilt"],
        tip=clf.TIPS.get(posture, ""),
        score=_rolling_score(state),
        alert=alert,
        low_light=critically_dark,
        issues=result["issues"],
    )


def _rolling_score(state: SessionState) -> int:
    """Score over the last SCORE_WINDOW_FRAMES frames."""
    recent = state.session_log[-config.SCORE_WINDOW_FRAMES:]
    if not recent:
        return 0
    good = sum(1 for _, p in recent if p == "Good Posture")
    return int(good / len(recent) * 100)


@app.post("/setup/{session_id}")
async def configure_camera_setup(session_id: str, camera_type: str = "integrated", position: str = "desk"):
    """
    Configures the user's camera hardware type and physical placement,
    tuning baseline thresholds for upward or downward camera angles.
    """
    state = _get_session(session_id)
    state.baseline = state.baseline or {}

    # Adjust vertical neck ratio threshold based on physical angle
    if position == "desk_low":
        # Upward angle from desk surface naturally compresses visible neck length
        state.baseline["vertical_ratio"] = 0.58
        state.baseline["perspective"] = 0.22
    elif position == "stand_eye":
        # Eye-level standard alignment
        state.baseline["vertical_ratio"] = 0.72
        state.baseline["perspective"] = 0.23
    elif position == "monitor_high":
        # Downward angle from top of tall external monitor
        state.baseline["vertical_ratio"] = 0.80
        state.baseline["perspective"] = 0.24

    return {"status": "configured", "camera_type": camera_type, "position": position}


@app.post("/settings/alert_threshold/{session_id}")
def set_alert_threshold(session_id: str, seconds: float = Query(..., ge=3, le=120)):
    """
    Customizes the sustained bad posture duration (in seconds) before an alert fires.
    """
    state = _get_session(session_id)
    state.alert_threshold_s = float(seconds)
    return {"status": "ok", "session_id": session_id, "alert_threshold_s": state.alert_threshold_s}


@app.post("/calibrate/{session_id}")
async def calibrate_posture(session_id: str, file: UploadFile):
    """
    Captures the user's current frame as their personal neutral baseline.
    """
    contents = await file.read()
    frame = cv2.imdecode(np.frombuffer(contents, np.uint8), cv2.IMREAD_COLOR)
    if frame is None:
        raise HTTPException(400, "Could not decode image.")

    frame = cv2.flip(frame, 1)
    rgb   = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
    res   = pose.process(rgb)

    if not res.pose_landmarks:
        raise HTTPException(400, "No person detected to calibrate.")

    state = _get_session(session_id)
    raw = clf.classify(res.pose_landmarks.landmark, mp_pose)
    if "metrics" in raw:
        state.baseline = raw["metrics"]
        return {"status": "calibrated", "baseline": state.baseline}
    return {"status": "ok"}


@app.post("/coach/{session_id}", response_model=CoachResponse)
async def get_coaching_report(session_id: str):
    """
    Ends the session: computes stats, asks Gemini for a coaching report,
    saves to database, and clears the in-memory buffer.
    """
    if coach is None:
        raise HTTPException(500, "GEMINI_API_KEY is not configured on the server.")

    state = _get_session(session_id)
    stats = compute_session_stats(state.session_log, state.spine_history)
    if not stats:
        raise HTTPException(400, "No posture data recorded yet for this session.")

    try:
        report = await coach.analyse(stats)
    except CoachError as e:
        raise HTTPException(e.status_code, e.message)

    database.log_session(stats, label="Session end", ai_report=report)
    _sessions[session_id] = SessionState()   # reset for next session

    return CoachResponse(report=report, stats=stats)


