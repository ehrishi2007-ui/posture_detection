@app.get("/stats/summary", response_model=StatsSummaryResponse)
def get_stats_summary(days: int = 7):
    """
    Aggregated analytics for the Dashboard screen.
    Returns today's score, session count, monitored time, 7-day trend,
    posture breakdown, longest streak, and the last session record.
    """
    all_sessions = database.get_all_sessions(limit=500)

    today_str = date.today().isoformat()
    today_sessions = [
        s for s in all_sessions
        if s["timestamp"].startswith(today_str)
    ]

    # ── Today's score: weighted average across today's sessions ──────────────
    if today_sessions:
        today_score = int(sum(s["score"] for s in today_sessions) / len(today_sessions))
        today_monitored = sum(s["duration_min"] for s in today_sessions)
    else:
        today_score      = 0
        today_monitored  = 0.0

    # ── Today's posture breakdown: sum posture_counts across today's sessions ─
    today_breakdown: dict[str, int] = {}
    for s in today_sessions:
        for label, count in s.get("posture_counts", {}).items():
            today_breakdown[label] = today_breakdown.get(label, 0) + count

    # ── Longest good posture streak today ────────────────────────────────────
    # Approximated from session worst_streak (inverse — sessions with worst_streak=0
    # had sustained good posture). Better tracking can be added later.
    longest_streak_today = max(
        (s["score"] for s in today_sessions), default=0
    )

    # ── Daily scores for trend chart ─────────────────────────────────────────
    daily_scores = []
    day_names = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
    for i in range(days - 1, -1, -1):
        target = (date.today() - timedelta(days=i)).isoformat()
        day_sessions = [s for s in all_sessions if s["timestamp"].startswith(target)]
        score = int(sum(s["score"] for s in day_sessions) / len(day_sessions)) if day_sessions else 0
        day_label = day_names[(date.today() - timedelta(days=i)).weekday()]
        daily_scores.append({"day": day_label, "score": score, "date": target})

    # ── Last session ─────────────────────────────────────────────────────────
    last_session = None
    if all_sessions:
        s = all_sessions[0]   # already ordered DESC by id
        last_session = {
            "id":           s["id"],
            "timestamp":    s["timestamp"],
            "score":        s["score"],
            "duration_min": s["duration_min"],
            "top_issue":    s["top_issue"],
            "tip":          s["tip"],
        }

    return StatsSummaryResponse(
        today_score=today_score,
        today_sessions=len(today_sessions),
        today_monitored_min=round(today_monitored, 1),
        daily_scores=daily_scores,
        today_breakdown=today_breakdown,
        longest_streak_today=longest_streak_today,
        last_session=last_session,
    )
