"""
main.py

FastAPI backend for the posture monitoring app. Replaces the old Tkinter
main.py — same detection logic, but served over HTTP so a web frontend
(React / Electron renderer) can call it.

Key design decisions worth being able to explain in an interview:
- Webcam capture happens in the BROWSER, not here. The backend never
  touches cv2.VideoCapture — it receives individual frames as uploads.
  This is what makes it deployable on a server with no camera attached.
- Majority-vote smoothing (5-frame buffer, reduced from 10 for faster
  label response) and session history need to persist BETWEEN requests,
  but HTTP requests are stateless. Per-session state is kept in an
  in-memory dict keyed by session_id generated by the frontend per tab.
- Desktop notifications (plyer) are dropped — /analyze returns an
  "alert" flag when bad posture has persisted for 10+ seconds, and
  the Electron main process decides how to surface it (OS notification).
- v2: Expanded AnalyzeResponse with neck_angle, head_tilt, and issues.
      Added /stats/summary for the dashboard analytics screen.
      Classifier now uses env-configurable thresholds from config.py.
"""

import time
from collections import Counter, deque
from datetime import datetime, date, timedelta

import cv2
import mediapipe as mp
import numpy as np
from fastapi import FastAPI, HTTPException, UploadFile, Query
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel

import config
import database
from ai_coach import CoachError, PostureCoach, compute_session_stats
from posture_engine import PostureClassifier


# ─── App setup ────────────────────────────────────────────────────────────────

app = FastAPI(title="Meru Posture API", version="2.1.0")

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)

mp_pose = mp.solutions.pose
pose = mp_pose.Pose(min_detection_confidence=0.6, min_tracking_confidence=0.6)

# Classifier instantiated with env-configured thresholds so Settings screen
# changes (written to .env) take effect on next backend restart.
clf = PostureClassifier(thresholds=config.get_posture_thresholds())

coach = PostureCoach(api_key=config.GEMINI_API_KEY) if config.GEMINI_API_KEY else None

ROLLING_REPORT_INTERVAL_S = 300   # 5 minutes
BAD_POSTURE_ALERT_S       = 10    # seconds before alert fires


@app.on_event("startup")
def on_startup():
    database.init_db()


# ─── Per-session in-memory state ──────────────────────────────────────────────


class SessionState:
    def __init__(self):
        self.smoothing_buf  = deque(maxlen=config.SMOOTHING_BUFFER_SIZE)
        self.session_log:   list[tuple[datetime, str]] = []
        self.rolling_log:   list[tuple[datetime, str]] = []
        self.spine_history: list[float] = []
        self.bad_start:     float | None = None
        self.last_report_time: float = time.time()
        self.baseline:      dict | None = None
        self.alert_threshold_s: float = 10.0


_sessions: dict[str, SessionState] = {}


def _get_session(session_id: str) -> SessionState:
    if session_id not in _sessions:
        _sessions[session_id] = SessionState()
    return _sessions[session_id]


# ─── Request / response models ────────────────────────────────────────────────


class AnalyzeResponse(BaseModel):
    posture:       str
    spine_angle:   float
    shoulder_tilt: float
    neck_angle:    float    # ear-ahead-of-shoulder offset (forward head proxy)
    head_tilt:     float    # ear height asymmetry
    tip:           str
    score:         int
    alert:         bool
    low_light:     bool = False  # True if lighting is critically dim
    issues:        list[str]  # all triggered issues this frame (for live breakdown)


class CoachResponse(BaseModel):
    report: str
    stats:  dict


class StatsSummaryResponse(BaseModel):
    today_score:         int
    today_sessions:      int
    today_monitored_min: float
    daily_scores:        list[dict]   # [{ "day": "Mon", "score": int }, ...]
    today_breakdown:     dict         # { "Good Posture": int, ... }
    longest_streak_today: int
    last_session:        dict | None  # None if no sessions yet


# ─── Routes ───────────────────────────────────────────────────────────────────


