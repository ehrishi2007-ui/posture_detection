"""
main.py

FastAPI backend for the posture monitoring app. Replaces the old Tkinter
main.py — same detection logic, but served over HTTP so a web frontend
(Streamlit or React) can call it.

Key design decisions worth being able to explain in an interview:
- Webcam capture happens in the BROWSER, not here. The backend never
  touches cv2.VideoCapture — it receives individual frames as uploads.
  This is what makes it deployable on a server with no camera attached.
- Majority-vote smoothing (10-frame buffer) and session history need to
  persist BETWEEN requests, but HTTP requests are stateless. So per-session
  state (smoothing buffer, frame log, spine history) is kept in an
  in-memory dict keyed by session_id, generated by the frontend per
  browser tab. Good enough for a single-user portfolio demo. If this needed
  to support many concurrent real users reliably across server restarts,
  this state would move to Redis instead of a Python dict.
- Desktop notifications (plyer) are dropped — that's an OS-level concept
  that doesn't exist on a server. Instead, /analyze returns an "alert"
  flag when bad posture has persisted for 10+ seconds, and the frontend
  decides how to surface that (toast, sound, etc.).
"""

import time
from collections import Counter, deque
from datetime import datetime

import cv2
import numpy as np
import mediapipe as mp
from fastapi import FastAPI, UploadFile, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel

import config
import database
from posture_engine import PostureClassifier
from ai_coach import PostureCoach, compute_session_stats, CoachError


# ─── App setup ────────────────────────────────────────────────────────────────

app = FastAPI(title="Posture Monitor API")

# Allows a Streamlit/React frontend running on a different port to call this
# API during local dev. Tighten this to your actual deployed frontend URL
# before shipping to production.
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)

mp_pose = mp.solutions.pose
pose = mp_pose.Pose(min_detection_confidence=0.6, min_tracking_confidence=0.6)
clf = PostureClassifier()
coach = PostureCoach(api_key=config.GEMINI_API_KEY) if config.GEMINI_API_KEY else None

ROLLING_REPORT_INTERVAL_S = 300  # 5 minutes, matches original app
BAD_POSTURE_ALERT_S = 10  # matches original app's notification trigger


@app.on_event("startup")
def on_startup():
    database.init_db()


# ─── Per-session in-memory state ─────────────────────────────────────────────


class SessionState:
    def __init__(self):
        self.smoothing_buf = deque(maxlen=config.SMOOTHING_BUFFER_SIZE)
        self.session_log: list[
            tuple[datetime, str]
        ] = []  # permanent, feeds the AI coach
        self.rolling_log: list[tuple[datetime, str]] = []  # cleared every 5 min
        self.spine_history: list[float] = []
        self.bad_start: float | None = None
        self.last_report_time: float = time.time()


_sessions: dict[str, SessionState] = {}


def get_session(session_id: str) -> SessionState:
    if session_id not in _sessions:
        _sessions[session_id] = SessionState()
    return _sessions[session_id]


# ─── Request/response models ─────────────────────────────────────────────────


class AnalyzeResponse(BaseModel):
    posture: str
    spine_angle: float
    shoulder_tilt: float
    tip: str
    score: int
    alert: bool


class CoachResponse(BaseModel):
    report: str
    stats: dict


# ─── Routes ───────────────────────────────────────────────────────────────────


@app.get("/health")
def health():
    return {"status": "ok"}


@app.post("/analyze", response_model=AnalyzeResponse)
async def analyze_frame(session_id: str, file: UploadFile):
    """
    Accepts one JPEG/PNG frame from the browser, runs MediaPipe + the
    posture classifier, applies majority-vote smoothing, and updates this
    session's rolling score. Call this repeatedly (e.g. every 500ms) from
    the frontend to simulate continuous monitoring.
    """
    contents = await file.read()
    frame = cv2.imdecode(np.frombuffer(contents, np.uint8), cv2.IMREAD_COLOR)
    if frame is None:
        raise HTTPException(400, "Could not decode image — check the upload format.")

    state = get_session(session_id)

    frame = cv2.flip(frame, 1)
    rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
    res = pose.process(rgb)

    if not res.pose_landmarks:
        return AnalyzeResponse(
            posture="No Pose Detected",
            spine_angle=0.0,
            shoulder_tilt=0.0,
            tip="",
            score=_rolling_score(state),
            alert=False,
        )

    result = clf.classify(res.pose_landmarks.landmark, mp_pose)
    posture = result["posture"]

    # Majority-vote smoothing over the last N frames — stops rapid flickering
    state.smoothing_buf.append(posture)
    posture = Counter(state.smoothing_buf).most_common(1)[0][0]

    now = datetime.now()
    state.session_log.append((now, posture))
    state.rolling_log.append((now, posture))
    if result["spine_angle"]:
        state.spine_history.append(result["spine_angle"])

    # Sustained bad-posture alert (replaces the old OS notification)
    alert = False
    if posture != "Good Posture":
        if state.bad_start is None:
            state.bad_start = time.time()
        elif time.time() - state.bad_start >= BAD_POSTURE_ALERT_S:
            alert = True
            state.bad_start = time.time()  # reset so alert re-fires periodically
    else:
        state.bad_start = None

    # Periodic 5-min report, same cadence as the original app
    if time.time() - state.last_report_time >= ROLLING_REPORT_INTERVAL_S:
        stats = compute_session_stats(state.rolling_log, state.spine_history)
        if stats:
            database.log_session(stats, label="5-min check")
        state.rolling_log.clear()
        state.last_report_time = time.time()

    return AnalyzeResponse(
        posture=posture,
        spine_angle=result["spine_angle"],
        shoulder_tilt=result["shoulder_tilt"],
        tip=clf.TIPS.get(posture, ""),
        score=_rolling_score(state),
        alert=alert,
    )


def _rolling_score(state: SessionState) -> int:
    """Score over the last SCORE_WINDOW_FRAMES frames, matching the original app."""
    recent = state.session_log[-config.SCORE_WINDOW_FRAMES :]
    if not recent:
        return 0
    good = sum(1 for _, p in recent if p == "Good Posture")
    return int(good / len(recent) * 100)


@app.post("/coach/{session_id}", response_model=CoachResponse)
async def get_coaching_report(session_id: str):
    """
    Ends the session: computes stats from everything logged so far,
    asks Gemini for a coaching report, saves the session to the database,
    and clears the in-memory buffer.
    """
    if coach is None:
        raise HTTPException(500, "GEMINI_API_KEY is not configured on the server.")

    state = get_session(session_id)
    stats = compute_session_stats(state.session_log, state.spine_history)
    if not stats:
        raise HTTPException(400, "No posture data recorded yet for this session.")

    try:
        report = await coach.analyse(stats)
    except CoachError as e:
        raise HTTPException(e.status_code, e.message)

    database.log_session(stats, label="Session end")

    # Reset this session's in-memory state so a new session starts clean
    _sessions[session_id] = SessionState()

    return CoachResponse(report=report, stats=stats)


@app.get("/sessions")
def list_sessions(limit: int = 50):
    return database.get_all_sessions(limit=limit)


@app.get("/sessions/{session_id}")
def get_session_record(session_id: int):
    record = database.get_session(session_id)
    if record is None:
        raise HTTPException(404, "Session not found.")
    return record
